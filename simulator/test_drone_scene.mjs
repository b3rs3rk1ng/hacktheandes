import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import * as THREE from './ui/vendor/three.module.js';
import {createGuardedDrone} from './ui/drone/guarded-airframe.js';
import {createMountedCameraRig} from './ui/drone/camera-rig.js';
import {RotorState} from './ui/drone/rotor-core.mjs';
const cfg=JSON.parse(readFileSync(new URL('./orchard_config.json',import.meta.url)));
const model=createGuardedDrone(cfg),body=model.root;
assert.ok(body.userData.batching.after<body.userData.batching.before/2);
assert.equal(model.rotors.length,cfg.flight.rotors);
body.position.set(3,2,-4);body.quaternion.setFromEuler(new THREE.Euler(.12,.7,.08));
const camera=new THREE.PerspectiveCamera(58),offset=new THREE.Vector3(.235,-.04,0),rig=createMountedCameraRig(camera,body,offset);
rig.update(1/60,new THREE.Vector3(8,2,-6));
const expected=offset.clone().applyQuaternion(body.quaternion).add(body.position);
assert.ok(camera.position.distanceTo(expected)<1e-10);
for(let n=0;n<100;n++)rig.update(1/60,new THREE.Vector3(-8,15,2));
assert.ok(Math.abs(rig.angles.yaw)<=.65);assert.ok(rig.angles.pitch<=.45);
const before=camera.position.clone();body.position.x+=1;rig.update(1/60,new THREE.Vector3(-8,15,2));assert.ok(Math.abs(camera.position.x-before.x-1)<1e-10);
const state=new RotorState(cfg.flight);for(let n=0;n<120;n++)state.update(1/60,23.544);model.update(state,camera.quaternion);
assert.ok(model.rotors.every(r=>r.blur.visible&&!r.spin.visible));
const mountOrientation=body.quaternion.clone().multiply(model.gimbal.quaternion),axis=new THREE.Vector3(1,0,0).applyQuaternion(mountOrientation),view=new THREE.Vector3(0,0,-1).applyQuaternion(camera.quaternion);
assert.ok(axis.distanceTo(view)<1e-8);
for(let n=0;n<240;n++)state.update(1/60,0);model.update(state,camera.quaternion);assert.ok(model.rotors.every(r=>r.spin.visible&&!r.blur.visible));
let meshes=0;body.traverse(o=>{if(o.isMesh){meshes++;for(const v of o.geometry.attributes.position.array)assert.ok(Number.isFinite(v))}});
console.log(JSON.stringify({test:'Airframe batching, geometry, camera mount/limits/gimbal optical alignment and rotor lifecycle passed',meshes,cageStruts:body.userData.cageStruts,batching:body.userData.batching}));
